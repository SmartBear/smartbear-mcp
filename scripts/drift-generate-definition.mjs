#!/usr/bin/env node
/**
 * Generates, from the tools the built server advertises:
 *  - src/pactflow/drift/pactflow.mcp.yaml: the MCP definition (SmartBear Studio format) of
 *    the PactFlow tools and prompt, the contract the Drift MCP plugin verifies
 *    the server against;
 *  - src/pactflow/drift/pactflow.tools.testcases.yaml: one tool call per tool, with
 *    arguments built from its input schema, for every tool that the
 *    hand-written src/pactflow/drift/pactflow.testcases.yaml does not already call.
 *
 * Regenerate both whenever the PactFlow tools change:
 *
 *   npm run build && npm run drift:generate
 */
import { spawn } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";
import { startMock } from "../src/pactflow/drift/mock-pactflow.mjs";

const root = fileURLToPath(new URL("..", import.meta.url));
const output = fileURLToPath(
  new URL("../src/pactflow/drift/pactflow.mcp.yaml", import.meta.url),
);
const curatedFile = fileURLToPath(
  new URL("../src/pactflow/drift/pactflow.testcases.yaml", import.meta.url),
);
const generatedFile = fileURLToPath(
  new URL(
    "../src/pactflow/drift/pactflow.tools.testcases.yaml",
    import.meta.url,
  ),
);

const fixturesFile = fileURLToPath(
  new URL(
    "../src/pactflow/drift/mock-fixtures.generated.json",
    import.meta.url,
  ),
);

const HEADER =
  "# Generated by scripts/drift-generate-definition.mjs - do not edit by hand.\n";
const TESTCASE_SCHEMA =
  "# yaml-language-server: $schema=https://download.pactflow.io/drift/schemas/drift.testcases.v1.schema.json\n";

const UUID = "00000000-0000-4000-8000-000000000001";
const b64 = (value) => Buffer.from(JSON.stringify(value)).toString("base64");
const PACT = {
  consumer: { name: "smartbear-mcp" },
  provider: { name: "pactflow-api" },
  interactions: [],
  metadata: { pactSpecification: { version: "3.0.0" } },
};
const OPENAPI = {
  openapi: "3.0.0",
  info: { title: "PactFlow API", version: "1.0.0" },
  paths: {},
};

/** Realistic values by input name, consistent with the mock's fixtures. */
const VALUES = {
  pacticipantName: "smartbear-mcp",
  pacticipant: "smartbear-mcp",
  consumerName: "smartbear-mcp",
  providerName: "pactflow-api",
  provider: "pactflow-api",
  versionNumber: "1.0.0",
  pacticipantVersionNumber: "1.0.0",
  providerVersionNumber: "1.0.0",
  consumerVersionNumber: "1.0.0",
  version: "1.0.0",
  branchName: "main",
  branch: "main",
  labelName: "frontend",
  environment: "production",
  environmentId: "00000000-0000-0000-0000-000000000002",
  email: "drift@example.com",
  name: "drift-example",
  displayName: "Drift Example",
  firstName: "Drift",
  lastName: "Example",
  description: "Created by a Drift test",
  value: "drift-secret-value",
  tag: "main",
  q: undefined,
  pageNumber: 1,
  pageSize: 10,
  page: 1,
  size: 10,
};
/** Optional inputs worth sending, so the calls exercise more than the required ones. */
const OPTIONAL_INPUTS = new Set(["pageNumber", "pageSize", "page", "size"]);

/** A value that satisfies a JSON schema: what it requires, with realistic values. */
function sample(schema, name = "example") {
  if (schema.const !== undefined) return schema.const;
  if (schema.enum) return schema.enum[0];
  const description = schema.description ?? "";
  if (/base64/i.test(description)) {
    return b64(/openapi|asyncapi/i.test(description) ? OPENAPI : PACT);
  }
  if (
    name in VALUES &&
    VALUES[name] !== undefined &&
    (schema.type === "string" || schema.type === "number" || !schema.type)
  ) {
    return typeof VALUES[name] === "number"
      ? Math.min(
          Math.max(VALUES[name], schema.minimum ?? 0),
          schema.maximum ?? Infinity,
        )
      : VALUES[name];
  }
  if (/\bUUID\b/i.test(description) || /Uuid$/.test(name)) return UUID;
  if (/ISO 8601/i.test(description)) return "2024-01-01T00:00:00.000Z";
  if (/Id$/.test(name) && schema.type === "string") return UUID;
  if (schema.const !== undefined) return schema.const;
  if (schema.enum) return schema.enum[0];
  if (schema.anyOf || schema.oneOf) {
    const options = schema.anyOf ?? schema.oneOf;
    return sample(options.find((o) => o.type !== "null") ?? options[0], name);
  }
  if (schema.allOf) {
    return Object.assign({}, ...schema.allOf.map((s) => sample(s, name)));
  }
  const type = Array.isArray(schema.type)
    ? schema.type.find((t) => t !== "null")
    : schema.type;
  switch (type) {
    case "string": {
      if (
        schema.format === "uuid" ||
        schema.pattern?.includes("[0-9a-fA-F]{8}")
      ) {
        return "00000000-0000-4000-8000-000000000001";
      }
      if (schema.format === "uri") return "https://example.com/drift";
      if (schema.format === "email") return "drift@example.com";
      if (schema.format === "date-time") return "2024-01-01T00:00:00.000Z";
      const value = name;
      return value.length >= (schema.minLength ?? 0)
        ? value
        : value.padEnd(schema.minLength, "x");
    }
    case "integer":
    case "number":
      return Math.min(
        Math.max(schema.minimum ?? 1, 1),
        schema.maximum ?? Infinity,
      );
    case "boolean":
      return true;
    case "array":
      return Array.from({ length: Math.max(schema.minItems ?? 0, 1) }, () =>
        sample(schema.items ?? {}, name),
      );
    case "object": {
      const result = {};
      const keys = [
        ...(schema.required ?? []),
        ...Object.keys(schema.properties ?? {}).filter(
          (key) => OPTIONAL_INPUTS.has(key) && !schema.required?.includes(key),
        ),
      ];
      for (const key of keys) {
        result[key] = sample(schema.properties?.[key] ?? {}, key);
      }
      return result;
    }
    default:
      return name;
  }
}

/**
 * A value for every property of an output schema (to a limited depth), so a
 * response has content to assert on. Unlike `sample`, which only fills what
 * is required.
 */
function fullSample(schema, name = "example", depth = 0, root = schema) {
  if (!schema || depth > 5) return undefined;
  if (schema.$ref) {
    const target = schema.$ref
      .replace(/^#\//, "")
      .split("/")
      .reduce((node, key) => node?.[key], root);
    return fullSample(target, name, depth + 1, root);
  }
  if (schema.const !== undefined) return schema.const;
  if (schema.enum) return schema.enum[0];
  if (schema.anyOf || schema.oneOf) {
    const options = schema.anyOf ?? schema.oneOf;
    return fullSample(
      options.find((o) => o.type !== "null") ?? options[0],
      name,
      depth,
      root,
    );
  }
  if (schema.allOf) {
    return Object.assign(
      {},
      ...schema.allOf.map((s) => fullSample(s, name, depth, root)),
    );
  }
  const type = Array.isArray(schema.type)
    ? schema.type.find((t) => t !== "null")
    : schema.type;
  if (type === "object") {
    const result = {};
    for (const [key, value] of Object.entries(schema.properties ?? {})) {
      const v = fullSample(value, key, depth + 1, root);
      if (v !== undefined) result[key] = v;
    }
    return result;
  }
  if (type === "array") {
    const item = fullSample(schema.items ?? {}, name, depth + 1, root);
    return item === undefined ? [] : [item];
  }
  return sample(schema, name);
}

// The same mock backend the Drift tests use, so the advertised tools match
// (PactFlow AI tools only appear when the entitlement check succeeds).
// Fixtures start empty and are learned below, so the generated calls always
// reflect the current tools rather than a previous run's fixtures.
const fixtures = {};
let lastRequest;
const { server: mock, port } = await startMock(0, {
  fixtures,
  onRequest: (key) => {
    lastRequest = key;
  },
});

const child = spawn("node", ["dist/index.js"], {
  cwd: root,
  env: {
    ...process.env,
    PACT_BROKER_BASE_URL: `http://127.0.0.1:${port}`,
    PACT_BROKER_TOKEN: "drift",
  },
  stdio: ["pipe", "pipe", "inherit"],
});

let nextId = 1;
const pending = new Map();
let buffer = "";
child.stdout.on("data", (chunk) => {
  buffer += chunk;
  for (let i = buffer.indexOf("\n"); i >= 0; i = buffer.indexOf("\n")) {
    const line = buffer.slice(0, i).trim();
    buffer = buffer.slice(i + 1);
    // The server also logs plain text to stdout; only JSON-RPC lines matter.
    if (!line.startsWith("{")) continue;
    const message = JSON.parse(line);
    pending.get(message.id)?.(message);
    pending.delete(message.id);
  }
});

const send = (message) =>
  child.stdin.write(`${JSON.stringify({ jsonrpc: "2.0", ...message })}\n`);
const request = (method, params) =>
  new Promise((resolve, reject) => {
    const id = nextId++;
    const timer = setTimeout(
      () => reject(new Error(`${method} timed out`)),
      20_000,
    );
    pending.set(id, (message) => {
      clearTimeout(timer);
      message.error
        ? reject(new Error(message.error.message))
        : resolve(message.result);
    });
    send({ id, method, params });
  });

try {
  await request("initialize", {
    protocolVersion: "2025-06-18",
    capabilities: {},
    clientInfo: { name: "drift-generate-definition", version: "0" },
  });
  send({ method: "notifications/initialized" });

  const tools = [];
  let cursor;
  do {
    const result = await request("tools/list", cursor ? { cursor } : {});
    tools.push(...result.tools);
    cursor = result.nextCursor;
  } while (cursor);

  const prompts = [];
  cursor = undefined;
  do {
    const result = await request("prompts/list", cursor ? { cursor } : {});
    prompts.push(...result.prompts);
    cursor = result.nextCursor;
  } while (cursor);

  tools.sort((a, b) => a.name.localeCompare(b.name));
  const definition = {
    tools: tools.map(
      ({
        name,
        title,
        description,
        inputSchema,
        outputSchema,
        annotations,
      }) => ({
        name,
        ...(title && { title }),
        description,
        inputSchema,
        ...(outputSchema && { outputSchema }),
        ...(annotations && { annotations }),
      }),
    ),
  };
  if (prompts.length > 0) {
    prompts.sort((a, b) => a.name.localeCompare(b.name));
    definition.prompts = prompts.map(
      ({ name, title, description, arguments: args }) => ({
        name,
        ...(title && { title }),
        ...(description && { description }),
        ...(args && { arguments: args }),
      }),
    );
  }
  writeFileSync(
    output,
    HEADER + yaml.dump(definition, { lineWidth: -1, noRefs: true }),
  );

  const curated = yaml.load(readFileSync(curatedFile, "utf8"));
  const covered = new Set(
    Object.values(curated.operations)
      .map((operation) => operation.target)
      .filter((target) => target.startsWith("pactflow:tool/"))
      .map((target) => target.slice("pactflow:tool/".length)),
  );
  const operations = {};
  const skipped = [];
  for (const tool of tools.filter((t) => !covered.has(t.name))) {
    const args = sample(tool.inputSchema);
    const expected = { result: { isError: false } };

    // Learn which endpoint the tool calls, serve a body built from its
    // outputSchema there, and expect the content the tool returns for it.
    const body = tool.outputSchema && fullSample(tool.outputSchema);
    if (body && Object.keys(body).length > 0) {
      lastRequest = undefined;
      await request("tools/call", { name: tool.name, arguments: args });
      const key = lastRequest;
      // The AI tools poll and fetch several endpoints; they keep hand-written
      // fixtures in the mock, so only the last call would be recorded here.
      if (key && !key.includes("/api/ai/")) {
        fixtures[key] = body;
        const result = await request("tools/call", {
          name: tool.name,
          arguments: args,
        });
        // Some tools reshape the response (e.g. list tools normalise
        // `pagination` and drop `_links`), so assert on what they return.
        if (result.isError || !result.structuredContent) {
          delete fixtures[key];
          skipped.push(`${tool.name} (${key}: tool error)`);
        } else {
          expected.result.structuredContent = result.structuredContent;
        }
      } else {
        skipped.push(`${tool.name} (${key ?? "no request"})`);
      }
    }
    operations[`${tool.name.replace(/^contract-testing_/, "")}_Success`] = {
      target: `pactflow:tool/${tool.name}`,
      parameters: { arguments: args },
      expected,
    };
  }
  writeFileSync(fixturesFile, `${JSON.stringify(fixtures, null, 2)}\n`);
  writeFileSync(
    generatedFile,
    HEADER +
      TESTCASE_SCHEMA +
      yaml.dump(
        {
          "drift-testcase-file": "v1",
          title: "PactFlow MCP tools (generated calls)",
          sources: [{ name: "pactflow", path: "./pactflow.mcp.yaml" }],
          plugins: [{ name: "mcp" }, { name: "json" }],
          operations,
        },
        { lineWidth: -1, noRefs: true },
      ),
  );
  console.log(
    `Wrote ${Object.keys(operations).length} generated tool calls to ${generatedFile}`,
  );
  console.log(
    `Wrote ${Object.keys(fixtures).length} mock fixtures to ${fixturesFile}`,
  );
  if (skipped.length > 0) {
    console.log(`No response content asserted for: ${skipped.join("; ")}`);
  }
  console.log(
    `Wrote ${tools.length} tools and ${prompts.length} prompts to ${output}`,
  );
} finally {
  child.kill();
  mock.close();
}
